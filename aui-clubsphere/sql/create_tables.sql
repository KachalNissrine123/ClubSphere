
-- Drop tables in reverse dependency order (safe re-run)
DROP TABLE IF EXISTS EXPENSE CASCADE;
DROP TABLE IF EXISTS SPONSORSHIP CASCADE;
DROP TABLE IF EXISTS ATTENDANCE CASCADE;
DROP TABLE IF EXISTS MEMBERSHIP CASCADE;
DROP TABLE IF EXISTS BUDGET CASCADE;
DROP TABLE IF EXISTS EVENT CASCADE;
DROP TABLE IF EXISTS SPONSOR CASCADE;
DROP TABLE IF EXISTS CLUB CASCADE;
DROP TABLE IF EXISTS CLUB_CATEGORY CASCADE;
DROP TABLE IF EXISTS ROLE CASCADE;
DROP TABLE IF EXISTS VENUE CASCADE;
DROP TABLE IF EXISTS ADMIN CASCADE;
DROP TABLE IF EXISTS LOGIN CASCADE;
DROP TABLE IF EXISTS STUDENT CASCADE;
DROP TABLE IF EXISTS APP_USER CASCADE;
DROP TABLE IF EXISTS budget_transaction CASCADE;


-- APP_USER
CREATE TABLE APP_USER (
    USER_ID     VARCHAR(20) PRIMARY KEY,
    USER_FNAME  VARCHAR(50) NOT NULL,
    USER_LNAME  VARCHAR(50) NOT NULL,
    USER_EMAIL  VARCHAR(100) UNIQUE NOT NULL,
    USER_PHONE  VARCHAR(20)
);

-- LOGIN
CREATE TABLE LOGIN (
    LOGIN_ID      SERIAL PRIMARY KEY,
    USER_ID       VARCHAR(20) NOT NULL UNIQUE REFERENCES APP_USER(USER_ID) ON DELETE CASCADE,
    USER_PASSWORD TEXT NOT NULL,
    LAST_LOGIN    TIMESTAMP
);

-- ADMIN
CREATE TABLE ADMIN (
    USER_ID        VARCHAR(20) PRIMARY KEY REFERENCES APP_USER(USER_ID) ON DELETE CASCADE,
    ADMIN_POSITION VARCHAR(100),
    ADMIN_OFFICE   VARCHAR(100)
);

-- STUDENT
CREATE TABLE STUDENT (
    USER_ID    VARCHAR(20) PRIMARY KEY REFERENCES APP_USER(USER_ID) ON DELETE CASCADE,
    STU_MAJOR  VARCHAR(50) NOT NULL,
    STU_YEAR   INT NOT NULL CHECK (STU_YEAR BETWEEN 1 AND 6)
);

-- ROLE
CREATE TABLE ROLE (
    ROLE_ID          SERIAL PRIMARY KEY,
    ROLE_NAME        VARCHAR(50) NOT NULL UNIQUE,
    ROLE_DESCRIPTION TEXT
);

-- VENUE
CREATE TABLE VENUE (
    VENUE_ID       SERIAL PRIMARY KEY,
    VENUE_NAME     VARCHAR(100) NOT NULL UNIQUE,
    VENUE_CAPACITY INT CHECK (VENUE_CAPACITY >= 0),
    VENUE_LOCATION VARCHAR(100)
);

-- CLUB_CATEGORY
CREATE TABLE CLUB_CATEGORY (
    CATEGORY_ID   SERIAL PRIMARY KEY,
    CATEGORY_NAME VARCHAR(100) NOT NULL UNIQUE
);

-- CLUB
CREATE TABLE CLUB (
    CLUB_ID          VARCHAR(20) PRIMARY KEY,
    CATEGORY_ID      INT NOT NULL REFERENCES CLUB_CATEGORY(CATEGORY_ID),
    CLUB_NAME        VARCHAR(100) NOT NULL UNIQUE,
    CLUB_FOUND_DATE  DATE,
    CLUB_DESCRIPTION TEXT
);

-- SPONSOR
CREATE TABLE SPONSOR (
    SPONSOR_ID    SERIAL PRIMARY KEY,
    SPONSOR_NAME  VARCHAR(100) NOT NULL UNIQUE,
    SPONSOR_TYPE  VARCHAR(50),
    SPONSOR_EMAIL VARCHAR(100) UNIQUE,
    SPONSOR_PHONE VARCHAR(20)
);

-- EVENT
CREATE TABLE EVENT (
    EVENT_ID          SERIAL PRIMARY KEY,
    CLUB_ID           VARCHAR(20) NOT NULL REFERENCES CLUB(CLUB_ID) ON DELETE CASCADE,
    VENUE_ID          INT REFERENCES VENUE(VENUE_ID),
    EVENT_NAME        VARCHAR(100) NOT NULL,
    EVENT_DATE        DATE,
    EVENT_STATUS      VARCHAR(20) NOT NULL DEFAULT 'Planned' CHECK (EVENT_STATUS IN ('Planned','Ongoing','Completed','Cancelled')),
    EVENT_DESCRIPTION TEXT
);

-- BUDGET
CREATE TABLE BUDGET (
    BUDGET_ID        SERIAL PRIMARY KEY,
    CLUB_ID          VARCHAR(20) NOT NULL REFERENCES CLUB(CLUB_ID) ON DELETE CASCADE,
    BUDGET_YEAR      INT NOT NULL,
    BUDGET_ALLOCATED NUMERIC(10,2) NOT NULL CHECK (BUDGET_ALLOCATED >= 0),
    BUDGET_SPENT     NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (BUDGET_SPENT >= 0),
    BUDGET_STATUS    VARCHAR(20) NOT NULL DEFAULT 'OK' CHECK (BUDGET_STATUS IN ('OK','OverBudget','UnderReview')),
    UNIQUE (CLUB_ID, BUDGET_YEAR)
);

-- MEMBERSHIP
CREATE TABLE MEMBERSHIP (
    MEMB_ID        SERIAL PRIMARY KEY,
    USER_ID        VARCHAR(20) NOT NULL REFERENCES STUDENT(USER_ID) ON DELETE CASCADE,
    CLUB_ID        VARCHAR(20) NOT NULL REFERENCES CLUB(CLUB_ID) ON DELETE CASCADE,
    ROLE_ID        INT REFERENCES ROLE(ROLE_ID),
    MEMB_JOIN_DATE DATE NOT NULL,
    MEMB_STATUS    VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (MEMB_STATUS IN ('Active','Inactive','Suspended')),
    UNIQUE (USER_ID, CLUB_ID)
);

-- ATTENDANCE
CREATE TABLE ATTENDANCE (
    ATT_ID        SERIAL PRIMARY KEY,
    USER_ID       VARCHAR(20) NOT NULL REFERENCES STUDENT(USER_ID) ON DELETE CASCADE,
    EVENT_ID      INT NOT NULL REFERENCES EVENT(EVENT_ID) ON DELETE CASCADE,
    ATT_STATUS    VARCHAR(20) NOT NULL CHECK (ATT_STATUS IN ('Present','Absent','Excused')),
    ATT_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (USER_ID, EVENT_ID)
);

-- SPONSORSHIP
CREATE TABLE SPONSORSHIP (
    SPONSOR_RECORD_ID SERIAL PRIMARY KEY,
    SPONSOR_ID        INT NOT NULL REFERENCES SPONSOR(SPONSOR_ID) ON DELETE CASCADE,
    CLUB_ID           VARCHAR(20) NOT NULL REFERENCES CLUB(CLUB_ID) ON DELETE CASCADE,
    SPONS_AMOUNT      NUMERIC(10,2) NOT NULL CHECK (SPONS_AMOUNT >= 0),
    SPONS_DATE        DATE NOT NULL,
    SPONS_TYPE        VARCHAR(50)
);

-- EXPENSE
CREATE TABLE EXPENSE (
    EXPENSE_ID      SERIAL PRIMARY KEY,
    BUDGET_ID       INT NOT NULL REFERENCES BUDGET(BUDGET_ID) ON DELETE CASCADE,
    EXPENSE_AMOUNT  NUMERIC(10,2) NOT NULL CHECK (EXPENSE_AMOUNT >= 0),
    EXPENSE_DATE    DATE NOT NULL,
    EXPENSE_DESCRIPTION TEXT
);

-- TRANSACTIONS
CREATE TABLE budget_transaction (
    transaction_id      SERIAL PRIMARY KEY,
    club_id             VARCHAR(10) NOT NULL REFERENCES club(club_id) ON DELETE CASCADE,
    budget_id           INT REFERENCES budget(budget_id) ON DELETE SET NULL,
    transaction_date    DATE NOT NULL DEFAULT CURRENT_DATE,
    transaction_desc    VARCHAR(200) NOT NULL,
    transaction_amount  NUMERIC(10,2) NOT NULL,
    transaction_type    VARCHAR(20) NOT NULL DEFAULT 'Expense'
                         CHECK (transaction_type IN ('Expense', 'Income', 'Adjustment')),
    recorded_by         VARCHAR(100)
);

CREATE INDEX idx_budget_transaction_club ON budget_transaction(club_id);
